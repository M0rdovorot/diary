package summary

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"strings"

	"diary/internal/entry"
)

// promptBase — версия шаблона промпта. К ней добавляется хеш итогового текста: набор категорий
// меняется пользователем, и по сохранённой версии видно, каким именно промптом сделано извлечение.
const promptBase = "json-v3"

const promptHead = `Ты помощник, который превращает расшифровку голосового дневника в структурированные данные. Автор — один человек, он говорит о себе. Пиши на русском.

Верни ТОЛЬКО один JSON-объект, без пояснений и без markdown-блоков.

ГЛАВНЫЕ ПРАВИЛА
1. Используй только то, что сказано в расшифровке. Ничего не выдумывай и не додумывай.
2. Если про поле ничего не сказано — ставь null (для списков тоже null, не пустой список). Не пиши вместо этого «не упоминалось», «нет» или «не было».
3. false для да/нет-полей ставь только если автор ПРЯМО сказал, что этого не было (например: «не пил алкоголь», «сладкого не ел»). Если не сказано — null.
4. Сохраняй числа и детали как сказаны.
5. Расшифровка сделана автоматически и может содержать ошибки распознавания. Если слово явно искажено, исправь по смыслу, но не добавляй новых фактов.
6. Не оценивай, не морализируй, не давай советов. Пиши нейтрально и бережно.
7. Строковые поля — краткие, одна-две фразы. Поле diary — связный рассказ от первого лица («я»).
8. Автор может называть интимные темы любыми словами, в том числе прямо. Для них используй только соответствующие да/нет-поля (если они есть в списке ниже), а в текстовых полях (например, diary) пиши мягко: «гонение лысого» и «занятие любовью», не повторяя прямых слов.
9. Не относи информацию к категории по своему усмотрению. Если в подсказке категории сказано, что нужно прямое указание автора, без него ставь null.

СЕГМЕНТЫ И ДАТЫ
Один голосовой может рассказывать о нескольких днях (например: «сегодня было так… а вчера забыл сказать, что…»). Верни по одному сегменту на каждый день, о котором говорится. Внутри сегмента — только то, что сказано про этот день. Если автор добавляет что-то к уже рассказанному дню, в diary этого сегмента пиши только добавленное.

В начале сообщения пользователя указана опорная дата — день, к которому автор относит это голосовое (обычно день отправки, но автор мог выбрать другой день). Она нужна только чтобы пересчитать «сегодня», «вчера», «позавчера», «в понедельник» и т.п. в конкретную дату. Сама по себе опорная дата НЕ является датой, о которой говорится в записи.

Поля сегмента «date» и «date_source»:
— date: дата дня в формате ГГГГ-ММ-ДД. Если год не назван — год опорной даты. Если автор не назвал день и его нельзя вывести из слов — null. Не подставляй опорную дату, если автор ни о каком дне не говорил.
— date_source: "explicit" (автор назвал дату), "relative" (пересчитано из «сегодня»/«вчера» и т.п.), "unknown" (date = null).

ПОЛЯ СЕГМЕНТА
date, date_source — см. выше.
`

const promptTail = `
ФОРМАТ ОТВЕТА
{"segments": [ { "date": "ГГГГ-ММ-ДД или null", "date_source": "explicit|relative|unknown", ...все поля из списка выше } ]}
Включай в сегмент все поля из списка; те, про которые ничего не сказано, ставь в null.`

// BuildExtractPrompt собирает промпт извлечения из активных категорий. Вторым значением
// возвращает версию промпта для сохранения вместе с результатом.
func BuildExtractPrompt(schema entry.Schema) (prompt, version string) {
	var b strings.Builder
	b.WriteString(promptHead)
	for _, c := range schema.Active() {
		b.WriteString(categoryLine(c))
		b.WriteByte('\n')
	}
	b.WriteString(promptTail)
	prompt = b.String()

	sum := sha256.Sum256([]byte(prompt))
	return prompt, promptBase + "-" + hex.EncodeToString(sum[:])[:8]
}

// categoryLine — строка описания категории: «ключ — тип. Название: подсказка».
func categoryLine(c entry.Category) string {
	var typ string
	switch c.Kind {
	case entry.List:
		typ = "список строк"
	case entry.Number:
		typ = "число"
		if c.Unit != "" {
			typ += " (в " + oneLine(c.Unit, 20) + ")"
		}
	case entry.Bool:
		typ = "true/false/null"
	default:
		typ = "строка"
	}
	line := fmt.Sprintf("%s — %s. %s", c.Key, typ, oneLine(c.Title, 60))
	if hint := oneLine(c.Hint, 400); hint != "" {
		line += ": " + hint
	}
	return line
}

// oneLine сжимает пользовательский текст в одну строку ограниченной длины: он попадает в
// системный промпт, и переводы строк или огромные вставки там ни к чему.
func oneLine(s string, limit int) string {
	s = strings.Join(strings.Fields(s), " ")
	if r := []rune(s); len(r) > limit {
		s = string(r[:limit])
	}
	return s
}
