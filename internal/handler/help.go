package handler

import (
	"context"

	"github.com/go-telegram/bot"
	"github.com/go-telegram/bot/models"
)

const helpText = `Дневник-бот

Отправьте голосовое — я распознаю речь, разложу рассказ по дням и полям (настроение, питание, стул, сон, физическое состояние, работа, Катя, занятия, привычки, мысли) и сохраню. В ответ придёт запись по каждому дню, о котором вы рассказали.

КАК ЭТО РАБОТАЕТ
— Назвали день («вчера», «1 сентября») — запись попадёт в карточку этого дня. Не назвали и дату не вывести — я спрошу кнопками.
— Граница дня в дневнике — 05:00: голосовое, отправленное до 05:00, относится к предыдущему дню.
— Несколько голосовых об одном дне складываются в одну карточку. Что добавлено позже, помечается источником: «доп. запись 23:10» или «из записи от 05.09».
— Чего вы не говорили, отмечается «не упоминалось». «Нет» ставлю, только если вы прямо сказали, что этого не было.

КОМАНДЫ

/day [дата] — карточка дня, собранная из всех голосовых. Без даты — текущий день дневника. Примеры: /day, /day 01.09, /day 01.09.2026, /day вчера.

/date [дата] — выбрать день для новых голосовых. Пока день выбран, все новые голосовые считаются записанными в него, а «сегодня» и «вчера» считаются от него (удобно, когда наговариваете старые дни). Примеры: /date 01.09 — выбрать, /date — посмотреть текущий выбор, /date сброс — вернуть обычный режим. Выбор сохраняется, пока вы его не сбросите.

/edit [дата] — исправить расшифровку, если речь распознана неверно. Показывает последние голосовые (или за указанный день); выберите нужное, и я пришлю его текст. Дальше:
— «Найти и заменить»: пришлите строки «как было => как надо» (по одной в строке, регистр не важен, заменяются все совпадения);
— «Заменить целиком»: пришлите новый текст одним сообщением (до 4096 символов);
— «Пересобрать запись»: заново разобрать текущий текст.
После правки запись пересобирается; прежняя версия текста сохраняется в истории.

/pending — записи, для которых не уточнена дата. По каждой повторю вопрос.

/help — эта справка.

ДАТЫ можно писать так: 05.09, 05.09.2026, сегодня, вчера, позавчера.`

func (h *Handler) onHelp(ctx context.Context, b *bot.Bot, u *models.Update) {
	m := u.Message
	if !h.allowed(m.From) {
		return
	}
	h.send(ctx, b, m.Chat.ID, helpText)
}
