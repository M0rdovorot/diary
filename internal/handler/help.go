package handler

import (
	"context"

	"github.com/go-telegram/bot"
	"github.com/go-telegram/bot/models"
)

const helpText = `Дневник-бот

Пришлите голосовое или напишите текстом — я разложу рассказ по дням и категориям (настроение, питание, сон, работа, хобби, кино, литература, привычки, мысли и т.д.) и сохраню. Для каждого дня, о котором вы рассказали, придёт запись.

КАК ЭТО РАБОТАЕТ
— Любое обычное сообщение без «/» — это текстовая запись. Она обрабатывается так же, как голосовая, только без распознавания и подтверждения.
— После голосового я покажу расшифровку: «✓ Верно» подтверждает её, «✎ Править» открывает правку. Пока вы не подтвердили, запись помечена ⚠ (в карточке дня и в /pending).
— Назвали день («вчера», «1 сентября») — запись попадёт в карточку этого дня. Не назвали и дату не вывести — спрошу кнопками.
— Граница дня — 05:00: отправленное до 05:00 относится к предыдущему дню.
— Несколько записей об одном дне складываются в одну карточку; добавленное позже помечается источником («доп. запись 23:10», «из записи от 05.09»).
— Чего вы не говорили, отмечается «не упоминалось». «Нет» ставлю, только если вы прямо сказали, что этого не было. «Мысли для психолога» заполняю, только если вы сами так их назвали.

КОМАНДЫ

/day [дата] — карточка дня. Примеры: /day, /day 01.09, /day вчера.

/calendar — календарь (и кнопка «Календарь» слева от поля ввода): дни с записями выделены, ⚠ — есть неподтверждённые. День с записями — карточка и все записи: изменить текст, подтвердить, пересобрать, удалить (нажатие на значение в карточке открывает его запись). Пустой день или ✎ — новая текстовая запись. Там же — части без даты и неразобранные записи. Кнопка ☰ — категории (создать, изменить, скрыть, удалить, порядок), «↻ Пересобрать» — заново разобрать день или все записи с новыми категориями. Название категории в карточке открывает все её значения по дням. В форме новой записи можно записать голос: расшифровку сразу видно и можно поправить. О действиях в календаре я коротко пишу сюда.

/date — выбрать день для новых записей: «сегодня» и «вчера» считаются от него (удобно, когда наговариваете старые дни). Откроется календарь: листайте месяцы кнопками ‹ ›, нажмите на день (зелёный — сегодня, ✓ — выбранный). Кнопка «Сбросить» отменяет выбор. Текстом тоже можно: /date 01.09, /date сброс.

/pending — что ждёт внимания: записи без даты (повторю вопрос) и неподтверждённые расшифровки (выберите запись — подтвердите или исправьте).

/edit [дата] — исправить или удалить любую запись (последние или за день). Выберите запись, и я пришлю её текст: «Найти и заменить» (строки «как было => как надо»), «Заменить целиком» (до 4096 символов), «Пересобрать запись», «🗑 Удалить запись» (навсегда, после подтверждения; карточки дней пересоберутся без неё). Прежний текст сохраняется в истории, правка считается подтверждением.

/categories — категории записи: добавить свою (название, тип, подсказка для модели, группа), переименовать, изменить подсказку, порядок и группу, скрыть и вернуть. Изменения действуют на новые записи; для старых — /edit → «Пересобрать запись» или календарь → ☰ → «Пересобрать все дни».

/help — эта справка.

Даты: 05.09, 05.09.2026, сегодня, вчера, позавчера.`

func (h *Handler) onHelp(ctx context.Context, b *bot.Bot, u *models.Update) {
	m := u.Message
	if !h.allowed(m.From) {
		return
	}
	h.send(ctx, b, m.Chat.ID, helpText)
}
